create or replace function public.set_push_device_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end;
$$;

create trigger set_push_devices_updated_at
before update on public.push_devices
for each row
execute function public.set_push_device_updated_at();


-- ---------------------------------------------------------------------------
-- Uniqueness / indexes
-- ---------------------------------------------------------------------------

-- A provider/token identifies one active push endpoint globally.
--
-- This also makes account switching deterministic: register_push_device()
-- transfers ownership of an already-known token to the currently
-- authenticated account instead of allowing the same active token to point
-- at two users.
create unique index push_devices_provider_token_uidx
on public.push_devices (
  push_provider,
  push_token
);

-- A single app installation may have only one ACTIVE registration for a user.
-- Historical disabled registrations remain available for diagnostics.
create unique index push_devices_active_user_installation_uidx
on public.push_devices (
  user_id,
  installation_id
)
where enabled = true;

create index push_devices_active_user_idx
on public.push_devices (
  user_id,
  platform,
  last_seen_at desc
)
where enabled = true;

create index push_devices_installation_idx
on public.push_devices (
  installation_id
);


-- ---------------------------------------------------------------------------
-- Registration RPC
-- ---------------------------------------------------------------------------

create or replace function public.register_push_device(
  p_installation_id uuid,
  p_platform text,
  p_push_provider text,
  p_push_token text,
  p_project_id text default null,
  p_app_version text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_device_id uuid;
  v_platform text := pg_catalog.lower(
    pg_catalog.btrim(
      coalesce(p_platform, '')
    )
  );
  v_push_provider text := pg_catalog.lower(
    pg_catalog.btrim(
      coalesce(p_push_provider, '')
    )
  );
  v_push_token text := pg_catalog.btrim(
    coalesce(p_push_token, '')
  );
  v_project_id text := nullif(
    pg_catalog.btrim(
      coalesce(p_project_id, '')
    ),
    ''
  );
  v_app_version text := nullif(
    pg_catalog.btrim(
      coalesce(p_app_version, '')
    ),
    ''
  );
begin
  if v_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  if p_installation_id is null then
    raise exception 'An installation ID is required.';
  end if;

  if v_platform not in ('ios', 'android') then
    raise exception 'Unsupported push platform.';
  end if;

  if v_push_provider not in ('expo', 'apns', 'fcm') then
    raise exception 'Unsupported push provider.';
  end if;

  if v_push_token = '' then
    raise exception 'A push token is required.';
  end if;

  -- If this installation rotated to a new token, retain the old record for
  -- diagnostics but disable it before activating the replacement.
  update public.push_devices
  set
    enabled = false,
    disabled_at = pg_catalog.now(),
    disabled_reason = 'token-rotated',
    last_seen_at = pg_catalog.now()
  where user_id = v_user_id
    and installation_id = p_installation_id
    and enabled = true
    and (
      push_provider <> v_push_provider
      or push_token <> v_push_token
    );

  -- A push endpoint may belong to only one signed-in account at a time.
  --
  -- If the same app installation is used after signing into another Khedmat
  -- account, ownership is transferred to the current authenticated user.
  insert into public.push_devices (
    user_id,
    installation_id,
    platform,
    push_provider,
    push_token,
    project_id,
    app_version,
    enabled,
    last_registered_at,
    last_seen_at,
    disabled_at,
    disabled_reason,
    delivery_failure_count,
    last_delivery_error,
    last_delivery_error_at
  )
  values (
    v_user_id,
    p_installation_id,
    v_platform,
    v_push_provider,
    v_push_token,
    v_project_id,
    v_app_version,
    true,
    pg_catalog.now(),
    pg_catalog.now(),
    null,
    null,
    0,
    null,
    null
  )
  on conflict (push_provider, push_token)
  do update
  set
    user_id = excluded.user_id,
    installation_id = excluded.installation_id,
    platform = excluded.platform,
    project_id = excluded.project_id,
    app_version = excluded.app_version,
    enabled = true,
    last_registered_at = pg_catalog.now(),
    last_seen_at = pg_catalog.now(),
    disabled_at = null,
    disabled_reason = null,
    delivery_failure_count = 0,
    last_delivery_error = null,
    last_delivery_error_at = null
  returning id
  into v_device_id;

  return v_device_id;
end;
$$;


-- ---------------------------------------------------------------------------
-- Disable RPC
-- ---------------------------------------------------------------------------

create or replace function public.disable_push_device(
  p_installation_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_updated_count integer;
begin
  if v_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  if p_installation_id is null then
    raise exception 'An installation ID is required.';
  end if;

  update public.push_devices
  set
    enabled = false,
    disabled_at = pg_catalog.now(),
    disabled_reason = 'signed-out',
    last_seen_at = pg_catalog.now()
  where user_id = v_user_id
    and installation_id = p_installation_id
    and enabled = true;

  get diagnostics v_updated_count = row_count;

  return v_updated_count > 0;
end;
$$;


