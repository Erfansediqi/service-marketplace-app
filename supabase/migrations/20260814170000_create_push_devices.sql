-- Khedmat push-device registry
--
-- Purpose:
-- - Register push-capable app installations against authenticated users.
-- - Support multiple devices per user.
-- - Support iOS and Android from one schema.
-- - Support Expo Push Service initially while leaving room for direct APNs/FCM
--   later if Khedmat needs it.
-- - Handle token rotation and account switching safely.
-- - Never expose another user's push token to the mobile client.
--
-- Client write model:
-- - Authenticated clients do NOT insert/update/delete this table directly.
-- - Registration happens through public.register_push_device().
-- - Logout/device disable happens through public.disable_push_device().
-- - Clients may SELECT only their own rows.
--
-- Later:
-- - The push Edge Function will use service-role access to find active tokens,
--   record delivery failures, and disable permanently invalid tokens.

create table public.push_devices (
  id uuid primary key default gen_random_uuid(),

  user_id uuid not null
    references public.profiles(id)
    on delete cascade,

  -- Stable ID generated once by the Khedmat installation and kept locally.
  -- It is NOT an advertising/device hardware identifier.
  installation_id uuid not null,

  platform text not null
    check (platform in ('ios', 'android')),

  push_provider text not null default 'expo'
    check (push_provider in ('expo', 'apns', 'fcm')),

  push_token text not null,

  -- Expo/EAS project UUID when available. Kept nullable until N9.
  project_id text,

  app_version text,

  enabled boolean not null default true,

  last_registered_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),

  disabled_at timestamptz,
  disabled_reason text,

  delivery_failure_count integer not null default 0
    check (delivery_failure_count >= 0),

  last_delivery_error text,
  last_delivery_error_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  check (pg_catalog.btrim(push_token) <> ''),

  check (
    project_id is null
    or pg_catalog.btrim(project_id) <> ''
  ),

  check (
    app_version is null
    or pg_catalog.btrim(app_version) <> ''
  ),

  check (
    disabled_reason is null
    or pg_catalog.btrim(disabled_reason) <> ''
  ),

  check (
    (
      enabled = true
      and disabled_at is null
    )
    or
    enabled = false
  )
);

comment on table public.push_devices is
  'Push-capable Khedmat app installations. Client registration is controlled through security-definer RPCs.';

comment on column public.push_devices.user_id is
  'Authenticated Supabase user currently associated with this push installation.';

comment on column public.push_devices.installation_id is
  'Random app-installation UUID generated by Khedmat; not a hardware or advertising identifier.';

comment on column public.push_devices.push_provider is
  'Push token namespace: Expo initially; APNs/FCM reserved for future direct delivery.';

comment on column public.push_devices.push_token is
  'Push delivery token. Sensitive routing data; never readable by other users.';


